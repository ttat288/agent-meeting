  const fill = (s, args) => s.replace(/\{(\d+)\}/g, (m, i) => (i < args.length ? String(args[i] ?? '') : m));
  // tr('câu') hoặc tr`câu ${x}`
  function tr(s, ...args) {
    if (Array.isArray(s) && s.raw) {
      const key = s.reduce((a, p, i) => a + '{' + (i - 1) + '}' + p);
      return fill(lang === 'en' && EN.has(key) ? EN.get(key) : key, args);
    }
    return lang === 'en' && EN.has(s) ? fill(EN.get(s), args) : fill(s, args);
  }
  // HTML tĩnh: dịch từng đoạn chữ (giữ khoảng trắng hai đầu) và các thuộc tính placeholder/title/aria-label
  function apply(root) {
    if (lang !== 'en') return;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    for (let n; (n = w.nextNode());) {
      const t = n.nodeValue.replace(/\s+/g, ' ').trim();
      if (t && EN.has(t)) n.nodeValue = n.nodeValue.replace(/\S[\s\S]*\S|\S/, EN.get(t));
    }
    for (const e of root.querySelectorAll('[placeholder],[title],[aria-label]'))
      for (const a of ['placeholder', 'title', 'aria-label']) { const v = e.getAttribute(a); if (v && EN.has(v)) e.setAttribute(a, EN.get(v)); }
  }
  function setLang(l) { try { localStorage.setItem(KEY, l); } catch {} const u = new URL(location.href); u.searchParams.delete('lang'); location.replace(u.pathname + u.search + u.hash); }
  window.AgentMeetingI18n = { lang, tr, apply, setLang, EN };
